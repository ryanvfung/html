import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export const stripComments = (source) => source
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .split('\n')
  .map((line) => line.replace(/(^|\s)\/\/.*$/, '$1'))
  .join('\n');

export const parseTokens = (source) => {
  const tokens = [...stripComments(source).matchAll(/(--[a-z0-9-]+):\s*([^;]+);/g)]
    .map(([, name, value]) => ({ name, value: value.trim() }))
    .filter((token, index, all) => all.findIndex((other) => other.name === token.name) === index);
  for (const token of tokens) {
    if (/[;{}]/.test(token.value)) throw new Error(`gen-spec: unsafe value for ${token.name}`);
  }
  const overlay = tokens.find((token) => token.name === '--surface-overlay');
  if (!overlay || !overlay.value.includes(',')) throw new Error('gen-spec: rgba value not captured');
  return tokens;
};

export const renderArtifacts = (tokens) => {
  const q = JSON.stringify;
  const swatchTokens = tokens.filter((t) => /^--(orange|neutral)-/.test(t.name));
  const isScale = (name) => /^--text-(xs|sm|base|lg|xl|2xl|3xl|4xl)$/.test(name) || /^--space-\d+$/.test(name);
  const swatchClass = (token) => `sw-${token.name.slice(2)}`;
  const swatch = (token) => `      li.token-swatch\n        span.${swatchClass(token)}\n        code= ${q(token.name)}\n        small= ${q(token.value)}`;
  const row = (token) => `      li.token-row\n        code= ${q(token.name)}\n        small= ${q(token.value)}`;
  const swatches = swatchTokens.map(swatch).join('\n');
  const scales = tokens.filter((token) => isScale(token.name)).map(row).join('\n');
  const semantic = tokens.filter((token) => !/^--(orange|neutral)-/.test(token.name) && !isScale(token.name)).map(row).join('\n');
  const swatchStyle = swatchTokens.map((token) => `.${swatchClass(token)} { --swatch: ${token.value}; }`).join('\n');
  const pug = `//- AUTO-GENERATED by scripts/gen-spec.mjs — do not edit.\nmixin spec-tokens()\n  section\n    h2 Token swatches\n    ul.token-grid\n${swatches}\n  section\n    h2 Type and space scales\n    ul.token-list\n${scales}\n  section\n    h2 Semantic and density tokens (light theme values)\n    ul.token-list\n${semantic}\n`;
  const scss = `// AUTO-GENERATED by scripts/gen-spec.mjs — do not edit.\n@layer components {\n${swatchStyle}\n}\n`;
  return { pug, scss };
};

const main = () => {
  const root = resolve(import.meta.dirname, '..');
  const tokens = parseTokens(readFileSync(resolve(root, 'src/tokens/_tokens.scss'), 'utf8'));
  const { pug, scss } = renderArtifacts(tokens);
  writeFileSync(resolve(root, 'src/pug/_generated.pug'), pug);
  writeFileSync(resolve(root, 'src/styles/_spec-generated.scss'), scss);
  const overlay = tokens.find((token) => token.name === '--surface-overlay');
  console.log(`gen-spec: ${tokens.length} tokens; overlay=${overlay.value}`);
};

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) main();
